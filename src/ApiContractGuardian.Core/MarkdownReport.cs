using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using ApiContractGuardian.Core.Model;

namespace ApiContractGuardian.Core
{
    public static class MarkdownReport
    {
        public static string Build(ComparisonResult r)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# API Contract Guardian Report");
            sb.AppendLine();
            sb.AppendLine("| | Baseline | Candidate |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| Title | " + Esc(r.OldSpec.Title) + " | " + Esc(r.NewSpec.Title) + " |");
            sb.AppendLine("| Version | " + Esc(r.OldSpec.Version) + " | " + Esc(r.NewSpec.Version) + " |");
            sb.AppendLine("| Format | " + Esc(r.OldSpec.Format) + " | " + Esc(r.NewSpec.Format) + " |");
            sb.AppendLine("| Operations | " + r.OldSpec.Operations.Count + " | " + r.NewSpec.Operations.Count + " |");
            sb.AppendLine();

            if (r.BreakingCount > 0)
                sb.AppendLine("**Verdict: FAIL** - " + r.BreakingCount + " breaking change(s). Publishing this version can break existing clients.");
            else if (r.WarningCount > 0)
                sb.AppendLine("**Verdict: PASS WITH WARNINGS** - no breaking changes, but " + r.WarningCount + " change(s) need review.");
            else
                sb.AppendLine("**Verdict: PASS** - no breaking changes detected.");
            sb.AppendLine();
            sb.AppendLine("| Breaking | Warnings | Info | Accepted (suppressed) |");
            sb.AppendLine("|---:|---:|---:|---:|");
            sb.AppendLine("| " + r.BreakingCount + " | " + r.WarningCount + " | " + r.InfoCount + " | " + r.SuppressedCount + " |");
            sb.AppendLine();

            Section(sb, "Breaking changes", r.Active.Where(c => c.Severity == Severity.Breaking).ToList());
            Section(sb, "Warnings", r.Active.Where(c => c.Severity == Severity.Warning).ToList());
            Section(sb, "Non-breaking changes", r.Active.Where(c => c.Severity == Severity.Info).ToList());

            var sup = r.Changes.Where(c => c.Suppressed).ToList();
            if (sup.Count > 0)
            {
                sb.AppendLine("## Accepted changes (suppressed)");
                sb.AppendLine();
                sb.AppendLine("| Severity | Code | Operation | Location | Reason |");
                sb.AppendLine("|---|---|---|---|---|");
                foreach (var c in sup)
                    sb.AppendLine("| " + c.Severity + " | `" + c.Code + "` | `" + Esc(c.Operation) + "` | " + Esc(c.Location) + " | " + Esc(c.SuppressionReason) + " |");
                sb.AppendLine();
            }

            sb.AppendLine("---");
            sb.AppendLine("Generated by API Contract Guardian on " + DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm") + " UTC.");
            return sb.ToString();
        }

        static void Section(StringBuilder sb, string title, List<ApiChange> items)
        {
            if (items.Count == 0) return;
            sb.AppendLine("## " + title + " (" + items.Count + ")");
            sb.AppendLine();
            sb.AppendLine("| Code | Operation | Location | Details |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var c in items)
                sb.AppendLine("| `" + c.Code + "` | `" + Esc(c.Operation) + "` | " + Esc(c.Location) + " | " + Esc(c.Message) + " |");
            sb.AppendLine();
        }

        static string Esc(string s)
        {
            return (s ?? "").Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ");
        }
    }
}
